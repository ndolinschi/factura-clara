export type MessageKey = keyof typeof messages.ro;

export function t(locale: Locale, key: MessageKey): string {
  return messages[locale][key] ?? messages.ro[key];
}

export function utilityKindLabel(locale: Locale, kind: UtilityKind): string {
  return t(locale, kind);
}

export function statusLabel(locale: Locale, status: MonthStatus): string {
  const map: Record<MonthStatus, MessageKey> = {
    paid: "statusPaid",
    partial: "statusPartial",
    missing: "statusMissing",
    mismatch: "statusMismatch",
  };
  return t(locale, map[status]);
}
